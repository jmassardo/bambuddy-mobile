const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../src/i18n/resources');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const deltaPath = path.join(root, 'delta-manifest.json');
const delta = fs.existsSync(deltaPath) ? JSON.parse(fs.readFileSync(deltaPath, 'utf8')) : { chunks: [] };
const imports = [];
const catalogs = [];
const files = [];
for (const language of manifest.locales) {
  const variables = [];
  for (const chunk of [...manifest.chunks, ...delta.chunks]) {
    if (!fs.existsSync(path.join(root, language, `${chunk}.json`))) continue;
    const name = `resource${files.length}`;
    imports.push(`import ${name} from './${language}/${chunk}.json';`);
    variables.push(`...${name}`);
    files.push(`${language}/${chunk}.json`);
  }
  if (variables.length) catalogs.push(`  '${language}': { ${variables.join(', ')} },`);
}
const output = [
  '// Generated by scripts/generate-native-resources.js; static imports are required by Metro.',
  ...imports,
  'export const resourceCatalogs: Partial<Record<string, Record<string, string>>> = {',
  ...catalogs, '};',
  `export const bundledResourceFiles = ${JSON.stringify(files)} as const;`, '',
].join('\n');
fs.writeFileSync(path.join(root, 'generated.ts'), output);
console.log(`Bundled ${files.length} native resource files. Regenerate after integrating locale resources.`);
