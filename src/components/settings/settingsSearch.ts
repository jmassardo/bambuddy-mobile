export function searchSettings(query: string, index = SETTINGS_SEARCH_INDEX) {
  const words = query
    .toLowerCase()
    .replace(/[_-]/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  if (!words.length) return [];
  return index.filter(item => {
    const text = `${item.label} ${item.section} ${item.panel ?? ''} ${
      item.keywords ?? ''
    }`
      .toLowerCase()
      .replace(/[_-]/g, ' ');
    return words.every(word => text.includes(word));
  });
}
